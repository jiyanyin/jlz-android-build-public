    fun bodyCount(): Int = bodies.values.sumOf { it.size }
    fun choose(mood: JlzVoiceMood, ordinal: Int, atMs: Long): String {
        val day = Instant.ofEpochMilli(atMs).atZone(ZoneId.of("Asia/Shanghai")).toLocalDate().toEpochDay()
        val options = bodies.getValue(mood)
        return options[Math.floorMod(day * 7L + ordinal.toLong() * 17L, options.size.toLong()).toInt()]
    }
